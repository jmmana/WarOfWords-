export function normalizeAnswer(input: string): string {
  return input
    .toLowerCase()
    .trim()
    .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?'"]/g, '')
    .replace(/\s+/g, ' ');
}

export function checkAnswerCorrectness(userAnswer: string, acceptedList: string[]): boolean {
  const normUser = normalizeAnswer(userAnswer);
  if (!normUser) return false;
  return acceptedList.some((acc) => {
    const normAcc = normalizeAnswer(acc);
    return normUser === normAcc;
  });
}
